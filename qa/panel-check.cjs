// Run with Playwright available; uses actual movement code and a controlled heap.
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(__dirname, '..');
const fixture = `const buffer=new ArrayBuffer(4*1024*1024);const m={HEAP32:new Int32Array(buffer),HEAPF32:new Float32Array(buffer),HEAPU8:new Uint8Array(buffer)};
const h=m.HEAP32,f=m.HEAPF32;h[3362936/4]=4096;h[(4096+92)/4]=8192;h[(8192+40)/4]=2;h[(8192+36)/4]=5;h[3363016/4]=24576;h[(24576+92)/4]=28672;h[28672/4]=12288;h[(12288+24)/4]=16384;h[(12288+12)/4]=20480;f[(20480+40)/4]=10;f[(20480+12)/4]=5;f[(20480+16)/4]=5;f[(20480+20)/4]=1;f[(12288+60)/4]=6;f[(16384+120)/4]=6;h[(16384+136)/4]=256;
window.gameInstance={Module:m};window.__srInvincibility={status:'ready',enabled:true,setEnabled(value){this.enabled=Boolean(value)}};`;
const server=http.createServer((req,res)=>{
  res.setHeader('Content-Type','text/html; charset=utf-8');
  if(req.url==='/') return res.end('<iframe src="/mobile/games/snow-rider-3d/game.html" style="width:100%;height:95vh;border:0"></iframe>');
  if(req.url==='/mobile/games/snow-rider-3d/game.html') return res.end(`<html><body style="margin:0;background:#c6dfe8"><div id="gameContainer"><canvas tabindex="0" style="width:100%;height:100vh;display:block"></canvas></div><script>${fixture}</script>${['movement.js','loadouts.js','panel.js','content.js'].map(file=>`<script src="/${file}"></script>`).join('')}<script>requestAnimationFrame(()=>{});</script></body></html>`);
  const file=path.join(root,req.url.slice(1));
  if(path.dirname(file)!==root||!fs.existsSync(file)){res.writeHead(404);return res.end();}
  res.setHeader('Content-Type','application/javascript; charset=utf-8');res.end(fs.readFileSync(file));
});
(async()=>{
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  try{
    const page=await browser.newPage({viewport:{width:1000,height:720}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto('http://127.0.0.1:'+server.address().port+'/');
    const frame=page.frames().find(frame=>frame.url().endsWith('/game.html'));
    assert.equal(await frame.locator('#sr-controls').count(),1,'New controls panel must mount');
    assert.equal(await frame.locator('#srlivespeed').count(),1,'Live readouts must be present');
    await frame.waitForFunction(()=>document.querySelector('#sr-controls').shadowRoot.querySelector('#srlivescore')?.textContent==='5');
    await frame.evaluate(()=>gameInstance.Module.HEAP32[(8192+36)/4]=12345);
    await frame.waitForFunction(()=>document.querySelector('#sr-controls').shadowRoot.querySelector('#srlivescore').textContent==='12,345');
    await frame.locator('#srhead').click();
    assert.ok((await frame.locator('#srmini').innerText()).includes('12,345'));
    await frame.locator('#srhead').click();
    await frame.evaluate(()=>gameInstance.Module.HEAP32[(8192+36)/4]=5);
    assert.equal(await frame.locator('#srpresetmax').innerText(),'10,000×');
    assert.equal(await frame.locator('#srforwardspeed').getAttribute('max'),'10000');
    assert.equal(await frame.locator('#srboostnumber').getAttribute('max'),'10000');
    await frame.locator('#srpresetmax').click();
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(12288+60)/4]),60000);
    await frame.locator('#srjumpnumber').fill('8');await frame.locator('#srjumpnumber').press('Tab');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(20480+40)/4]),80);
    await frame.locator('#srflight').click();
    const rise=frame.locator('#srrise');
    await rise.hover();await page.mouse.down();
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]),16);
    await page.mouse.up();
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]),0);
    await rise.focus();await page.keyboard.down('Enter');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]),16);
    await page.keyboard.up('Enter');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]),0);
    await frame.locator('#srnormal').click();
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+120)/4]),6);
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAP32[(16384+136)/4]),256);
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(20480+40)/4]),10);
    await frame.locator('#srreset').click();
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(20480+40)/4]),40);
    await frame.locator('#srforwardnumber').fill('10');await frame.locator('#srforwardnumber').press('Tab');
    await frame.locator('#gameContainer canvas').click({position:{x:500,y:100}});
    await page.keyboard.down('b');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(12288+60)/4]),1800);
    await page.keyboard.up('b');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(12288+60)/4]),60);
    await frame.evaluate(()=>{gameInstance.Module.HEAPU8[16384+124]=0;gameInstance.Module.HEAPF32[(16384+116)/4]=10;__srMovement.tick();});
    await page.keyboard.press('ArrowUp');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]),40);
    await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]=-2);
    await page.keyboard.press('ArrowUp');
    assert.equal(await frame.evaluate(()=>gameInstance.Module.HEAPF32[(16384+116)/4]),-2);
    await frame.locator('#srloadouts summary').click();
    await frame.locator('#srloadoutname').fill('My ride');await frame.locator('#srloadoutsave').click();
    const profileId=await frame.locator('#srloadoutselect').inputValue();
    await frame.locator('#srnormal').click();
    await frame.locator('#srloadoutselect').selectOption(profileId);await frame.locator('#srloadoutapply').click();
    assert.equal(await frame.evaluate(()=>__srMovement.forwardSpeed),10);
    await frame.locator('#srhead').click();assert.equal(await frame.locator('#srbody').isVisible(),false);
    await page.keyboard.press('Alt+s');assert.equal(await frame.locator('#srbody').isVisible(),true);
    await frame.locator('#srjumpnumber').fill('6');await frame.locator('#srjumpnumber').press('Tab');
    await page.reload();
    const reloaded=page.frames().find(frame=>frame.url().endsWith('/game.html'));
    await reloaded.locator('#srjumpnumber').waitFor();
    assert.equal(await reloaded.locator('#srjumpnumber').inputValue(),'6');
    assert.equal(await reloaded.evaluate(()=>JSON.parse(localStorage.getItem('srBoost')).loadouts.length),1);
    await reloaded.evaluate(()=>{__srInvincibility.status='unsupported';requestAnimationFrame(()=>{});});
    await reloaded.waitForFunction(()=>document.querySelector('#sr-controls').shadowRoot.querySelector('#srinvincible').disabled);
    assert.equal(await reloaded.locator('#srflight').isDisabled(),true);
    await reloaded.evaluate(()=>{__srInvincibility.status='ready';requestAnimationFrame(()=>{});});
    await reloaded.waitForFunction(()=>!document.querySelector('#sr-controls').shadowRoot.querySelector('#srflight').disabled);
    await page.screenshot({path:process.env.PANEL_SCREENSHOT || '/tmp/snowrider-panel.png'});
    await page.setViewportSize({width:360,height:640});
    await reloaded.waitForFunction(()=>innerWidth<400);
    assert.equal(await reloaded.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.waitForTimeout(100);
    await page.screenshot({path:'/tmp/snowrider-panel-small.png'});
    assert.deepEqual(errors,[]);
    console.log('Panel checks passed: presets, numeric options, flight and boost holds, double jump, loadouts, normal/reset, shortcuts, refresh persistence, unsupported states and narrow layout.');
  }finally{await browser.close();server.close();}
})().catch(error=>{console.error(error);server.close();process.exitCode=1;});
